import { readdir, writeFile, rm } from "node:fs/promises";
import { readFileSync } from "node:fs";

const dir = "public/teams/logos";
const files = new Set(await readdir(dir));
const ratings = JSON.parse(
  readFileSync("public/data/worlds_mayhem_ratings.json", "utf8"),
);
const teams = [
  ...new Set(ratings.player_competition_scores.map((row) => row.team)),
].sort();

const ALIASES = {
  "Gen.G": "GenG",
  "ahq eSports Club": "ahq e-Sports Club",
  "KaBuM! Esports": "KaBuM e-Sports",
  "Unicorns of Love.CIS": "Unicorns of Love",
  "Fenerbahçe Esports": "1907 Fenerbahe Esports",
  TSM: "Team SoloMid",
  "Dplus Kia": "KOO Tigers",
  Griffin: "KOO Tigers",
  "Kiwoom DRX": "DRX",
  "MAD Lions KOI": "MAD Lions",
  "Oh My God": "OMG",
  "Team Secret Whales": "Team Whales",
};

const stem = (file) => file.replace(/\.webp$/i, "");
const available = new Set([...files].map(stem));

const resolved = [];
const initials = [];
for (const team of teams) {
  const candidate = ALIASES[team] ?? team;
  if (available.has(candidate)) resolved.push([team, candidate]);
  else initials.push(team);
}

const body = resolved
  .map(
    ([team, file]) =>
      `  ${JSON.stringify(team)}: ${JSON.stringify(`${file}.webp`)},`,
  )
  .join("\n");

const source = `// Team -> file name under public/teams/logos. Generated by
const TEAM_LOGOS: Record<string, string> = {
${body}
};
export function teamLogo(team: string): string | null {
  const file = TEAM_LOGOS[team];
  const env = (import.meta as unknown as { env?: { BASE_URL?: string } }).env;
  const base = env?.BASE_URL ?? "/";
  const prefix = base.endsWith("/") ? base : \`\${base}/\`;
  return file ? \`\${prefix}teams/logos/\${encodeURIComponent(file)}\` : null;
}
export function playerPhoto(player: string): string {
  const env = (import.meta as unknown as { env?: { BASE_URL?: string } }).env;
  const base = env?.BASE_URL ?? "/";
  const prefix = base.endsWith("/") ? base : \`\${base}/\`;
  return \`\${prefix}players/\${encodeURIComponent(player)}.webp\`;
}
`;

await writeFile("src/lib/logos.ts", source);
await rm("public/teams/logos.json", { force: true });

console.log(
  `src/lib/logos.ts written: ${resolved.length} of ${teams.length} teams`,
);
console.log(`no logo (initials): ${initials.length}`);
initials.forEach((team) => console.log(`  ${team}`));

const used = new Set(resolved.map(([, file]) => `${file}.webp`));
const unused = [...files].filter((f) => !used.has(f));
console.log(
  `\nlogos on disk: ${files.size} | used: ${used.size} | unused: ${unused.length}`,
);
if (unused.length) console.log(unused.join("\n"));
